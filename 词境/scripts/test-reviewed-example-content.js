"use strict";
const assert = require("node:assert/strict");
const { fingerprint, dictionaryWithCorrections, reviewSummary } = require("./reviewed-example-content");
const senses = [{ id: "n-1", partOfSpeech: "n.", sense: "协会" }];
const entry = { senseGroups: [{ id: "one", partOfSpeech: "n.", sense: "协会", sourceSenseIds: ["n-1"], contextReviewed: true, semanticDistinct: true }], examples: [{ senseId: "one", sentence: "A reviewed sentence.", translation: "经过复核的句子。", targetForm: "association" }] };
const dictionary = { association: { senses } };
const corrections = { entries: {}, reviews: {} };
const ledger = { entries: {} };
const assess = (candidate = entry, lexicon = dictionary) => reviewSummary({ association: candidate }, lexicon, corrections, ledger, ["association"]);
assert.deepEqual(assess().pending, ["association"], "generator flags must not count as semantic review");
ledger.entries.association = { status: "approved", fingerprint: fingerprint(entry, senses), reviewedAt: "2026-10-05", reviewer: "test-only", notes: "Test fixture.", sources: ["https://example.test/dictionary"] };
assert.equal(assess().reviewed, 1);
assert.deepEqual(assess({ ...entry, examples: [{ ...entry.examples[0], translation: "已改动。" }] }).pending, ["association"], "editing a translation invalidates approval");
assert.deepEqual(assess(entry, { association: { senses: [{ ...senses[0], sense: "社团" }] } }).pending, ["association"], "editing a dictionary invalidates approval");
assert.equal(fingerprint({ b: 2, a: 1 }, senses), fingerprint({ a: 1, b: 2 }, senses));
const changed = { ...entry, senseGroups: [{ ...entry.senseGroups[0], sourceSenseIds: ["missing"] }] };
assert.deepEqual(assess(changed).invalid, ["association"]);
assert.throws(() => dictionaryWithCorrections(dictionary, { ...corrections, dictionaryOverrides: { association: senses } }), /unsupported/);
corrections.entries.association = entry;
corrections.reviews.association = { source: "https://example.test/dictionary", decision: "Test-only decision." };
corrections.reviewFingerprints = { association: fingerprint(entry, senses) };
assert.equal(assess().reviewed, 1);
assert.deepEqual(dictionaryWithCorrections(dictionary, { ...corrections, dictionaryOverrides: { association: senses } }), dictionary);
assert.throws(() => dictionaryWithCorrections(dictionary, { ...corrections, dictionaryOverrides: { association: [...senses, ...senses] } }), /invalid/);
assert.deepEqual(reviewSummary({ association: entry, extra: entry }, dictionary, corrections, ledger, ["association"]).extraWords, ["extra"]);
delete ledger.entries.association;
assert.deepEqual(assess({ ...entry, examples: [{ ...entry.examples[0], translation: "已改动。" }] }).pending, ["association"]);
const oldEntry = corrections.entries.association;
corrections.entries.association = { ...entry, examples: [{ ...entry.examples[0], translation: "未经重新复核。" }] };
assert.deepEqual(assess(corrections.entries.association).pending, ["association"], "changing a targeted correction also invalidates review");
corrections.entries.association = oldEntry;
console.log("Semantic review gate regression checks passed (13 assertions).");
